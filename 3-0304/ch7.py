from collections import defaultdict

# raw_exchange_data = """ ...(你的原始資料)... """

closes, ups = defaultdict(list), defaultdict(int)

# 1. 字串拆解、轉型,並同時完成分類與漲跌統計
for line in raw_exchange_data.strip().splitlines():
    _, pair, o, c = line.split("|")
    cur, o, c = pair.split("/")[0], float(o), float(c)
    closes[cur].append(c)
    ups[cur] += c > o  # 收盤價 > 開盤價 則 +1

# 驗證資料完整性:每個幣別應有 30 天
assert all(len(p) == 30 for p in closes.values()), "資料天數不足 30 天"

# 2. 確認資料結構
print("【資料結構歸類】")
for cur, p in closes.items():
    print(f'"{cur}": {p}')

# 3. 統計指標與格式化輸出
print("\n" + "=" * 40 + "\n【統計指標結果】")
for cur, p in closes.items():
    print(f"幣別: {cur}\n"
          f"  - 最高收盤價: {max(p):.4f}\n"
          f"  - 最低收盤價: {min(p):.4f}\n"
          f"  - 平均收盤價: {round(sum(p) / len(p), 4):.4f}\n"
          f"  - 上漲總天數: {ups[cur]} 天\n" + "-" * 30)