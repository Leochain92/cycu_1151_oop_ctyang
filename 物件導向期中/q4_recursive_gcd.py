"""
第四題：使用遞迴計算最大公因數（20 分）

題目要求：
使用歐幾里得輾轉相除法原理，以「遞迴」方式計算兩數的最大公因數（GCD）。
限制：
- 本題輸入為非負整數，且至少一個數大於 0。
- 請勿使用 math.gcd()，本題目的是練習自行設計遞迴。

逐步引導：
1. 先思考什麼情況下可以直接得到答案，不必再呼叫函式（基底情況 / 停止條件）。
2. 將這個停止條件寫成 if，並在條件成立時使用 return。
3. 若尚未到停止條件，使用餘數縮小問題，遞迴呼叫時交換參數位置：gcd(b, a % b)。
4. 確認每次呼叫都會朝停止條件前進。
"""

def gcd(a, b):
    """
    使用遞迴計算整數 a 與 b 的最大公因數 (Greatest Common Divisor)。
    
    參數:
        a (int): 非負整數
        b (int): 非負整數（a, b 至少一個大於 0）
    回傳:
        int: a 與 b 的最大公因數
    """
    # 步驟 1 & 2: 基底條件（停止條件）
    # 當 b == 0 時，a 即為最大公因數，直接回傳 a
    if b == 0:
        return a
        
    # 步驟 3 & 4: 遞迴步驟
    # 利用輾轉相除法定理：gcd(a, b) = gcd(b, a % b)
    # 取餘數運算使得第二個參數嚴格遞減，保證最終 b 會收斂至 0
    return gcd(b, a % b)


