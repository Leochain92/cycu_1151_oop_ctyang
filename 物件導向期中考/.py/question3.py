"""
第三題：使用遞迴計算最大公因數（20 分）
自行實作 gcd(a, b)，不使用 math.gcd()。
輸入為非負整數，且至少一個數大於 0；不需處理負數或兩個輸入皆為 0。
"""


def gcd(a, b):
    """
    使用歐幾里得演算法（遞迴）計算 a 與 b 的最大公因數。

    Args:
        a: 非負整數
        b: 非負整數（至少一個 > 0）

    Returns:
        int: a 與 b 的最大公因數
    """
    # 停止條件：當 b 為 0 時，最大公因數就是 a
    if b == 0:
        return a
    # 遞迴步驟：縮小問題，每次呼叫 b 逐步變小趨近 0
    return gcd(b, a % b)


# ===== 基本測試 =====
print("--- 基本測試 ---")
print(f"gcd(55, 21) = {gcd(55, 21)}")   # 預期 1
print(f"gcd(24, 18) = {gcd(24, 18)}")   # 預期 6
print(f"gcd(7, 0)   = {gcd(7, 0)}")     # 預期 7

